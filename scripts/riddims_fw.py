#!/usr/bin/env python3
# Génère firmware/src/mt40/mt40_riddims.c : la banque des 38 riddims du
# « The Riddim Real Book (Tab) » pour le firmware MT-40X, à la suite des six
# rythmes du MT-40 (mt40_patterns.c).
#   - basse : décalages en demi-tons par rapport à la fondamentale de l'accord
#     tenu (le comportement MT-40), fondamentale de chaque mesure = première
#     note de basse de la mesure dans le livre ;
#   - shift[] : le décalage de fondamentale de la mesure 2 (les riddims à deux
#     accords, p. ex. Queen Majesty Dm7 -> G) ;
#   - batterie : les masques du style du riddim (one drop, rockers, steppers,
#     rocksteady, digital, dancehall) — rim -> caisse claire (le MT-40 n'a que
#     4 pistes) ;
#   - nappes d'accord : le skank reggae (contretemps de croche).
# La table complète (6 + 38 = 44 entrées) et mt40_npatterns sortent ici.
import json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from riddims_site import BOOK, DRUMS, clean_bars   # noqa: E402

SRC = Path("/home/z/my-project/scripts/riddims_final.json")
OUTS = [Path("/home/z/my-project/build-fw/MT-4OX/firmware/src/mt40/mt40_riddims.c"),
        Path("/home/z/my-project/firmware/src/mt40/mt40_riddims.c")]

SKANK = [(2, 1), (6, 1), (10, 1), (14, 1)]        # contretemps de croche, 1 pas

def bar_root_pitch(notes, root_pc):
    """la fondamentale de la mesure : l'octave de root_pc la plus proche de la
    moyenne des notes de la mesure, recadrée dans leur étendue."""
    lo = min(m for _, m, _ in notes)
    hi = max(m for _, m, _ in notes)
    avg = sum(m for _, m, _ in notes) / len(notes)
    p = root_pc + 12 * round(avg / 12)
    while p > hi + 2:
        p -= 12
    while p < lo - 2:
        p += 12
    return p

def mask(lane_steps, bars):
    """les pas d'une piste de batterie -> bitmask (mesure 1 : bits 0..15)."""
    m = 0
    for bi, steps in enumerate(lane_steps[:max(bars, 1)]):
        for s in steps:
            if s < 16:
                m |= 1 << (bi * 16 + s)
    return m

def gen():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    out = []
    header = """/* SPDX-License-Identifier: GPL-3.0-only
 * MT-40X riddim bank - GENERATED by scripts/riddims_fw.py, do not edit.
 * The 38 riddims of "The Riddim Real Book (Tab)" as MT-40 accompaniment
 * patterns, after the six MT-40 presets. Bass: semitone offsets from the held
 * chord's root, the MT-40 transposition behaviour; the root of each bar is the
 * bar's first bass note in the book. shift[] carries the second bar's chord
 * root (the two-chord riddims). Drums: the riddim's style (one drop, rockers,
 * steppers, rocksteady, digital, dancehall), rim hits folded into the snare
 * lane (the MT-40 has four drum lanes). Stabs: the reggae skank (8th offbeats).
 * Source: the tablatures of the book; to calibrate by ear. */
#include "mt40_types.h"
"""
    out.append(header)
    table = []
    for r in data:
        rid = r["id"].upper().replace("-", "_")
        book = BOOK[r["id"]]
        bars = clean_bars(r["bars"])
        nb = len(bars)
        lo, hi = r["bpm"]
        bpm = lo if lo == hi else round((lo + hi) / 2)
        # fondamentales par mesure
        roots_pc = [b[0][1] % 12 for b in bars]
        roots = [bar_root_pitch(b, pc) for b, pc in zip(bars, roots_pc)]
        # événements de basse : pas absolu 0..31, décalage relatif à la
        # fondamentale de la mesure, replié dans [-9, +16]
        ev, emap = [], {}
        for bi, bar in enumerate(bars):
            for st, midi, ln in bar:
                off = midi - roots[bi]
                while off < -9:
                    off += 12
                while off > 16:
                    off -= 12
                key = (bi * 16 + st, off)
                if key in emap:
                    emap[key] = max(emap[key], min(ln, 8))
                else:
                    emap[key] = min(ln, 8)
        for (step, off), ln in sorted(emap.items()):
            ev.append((step, off, ln))
        # shifts : fondamentale de chaque mesure relative à la première
        shifts = [rp - roots[0] for rp in roots] if nb == 2 else None
        # batterie du style -> les 4 pistes du MT-40 (rim -> snare)
        dr = DRUMS[r["style"]]
        kick = mask(dr["k"], nb)
        snare = mask([sorted(set(a + b)) for a, b in zip(dr["s"], dr["rm"])], nb)
        hatcl = mask(dr["hc"], nb)
        hatop = mask(dr["ho"], nb)
        fb = 0xF0000000 if nb == 2 else 0x0000F000        # fill : fin de la dernière mesure
        ob = 0x80000000 if nb == 2 else 0x00008000
        name = r["name"].upper()[:12]
        meta = f'The Riddim Real Book p.{r["page"]}'
        if book["lb"]:
            meta += f', {book["lb"]}' + (f' {book["y"]}' if book["y"] else "")
        out.append(f"/* {r['name']}" + (f" ({book['a']})" if book["a"] else "") + " */\n")
        out.append("static const mt40_bass_t bass_%s[] = {\n" % rid)
        for step, off, ln in ev:
            out.append("    {%d, %d, %d},\n" % (step, off, ln))
        out.append("};\n")
        out.append("static const mt40_chord_t chords_%s[] = {\n" % rid)
        for bi in range(nb):
            for st, ln in SKANK:
                out.append("    {%d, %d},\n" % (bi * 16 + st, ln))
        out.append("};\n")
        if shifts:
            out.append("static const int8_t shift_%s[] = {%s};\n" %
                       (rid, ", ".join(str(s) for s in shifts)))
        out.append("static const mt40_pattern_t pat_%s = {\n" % rid)
        out.append('    "%s", "%s",\n' % (name, r["name"].replace('"', "'")))
        out.append("    %d, 16,\n" % nb)
        out.append("    1,\n")
        out.append("    %d,\n" % bpm)
        out.append("    { 0x%08xu, 0x%08xu, 0x%08xu, 0x%08xu },\n" % (kick, snare, hatcl, hatop))
        out.append("    bass_%s, %d,\n" % (rid, len(ev)))
        out.append("    chords_%s, %d,\n" % (rid, nb * len(SKANK)))
        out.append("    0x%08xu,\n" % fb)
        out.append("    0x%08xu,\n" % ob)
        out.append("    0x0f000f00u,\n")
        out.append('    "%s",\n' % meta.replace('"', "'"))
        if shifts:
            out.append("    shift_%s,\n" % rid)
        else:
            out.append("    0,\n")
        out.append("};\n\n")
        table.append("&pat_%s" % rid)
    out.append("/* the whole accompaniment: the six MT-40 presets, then the bank */\n")
    out.append("extern const mt40_pattern_t pat_ROCK, pat_POPS, pat_SWING, pat_SLOWROCK, pat_SAMBA, pat_WALTZ;\n")
    out.append("static const mt40_pattern_t *const mt40_pattern_table[%d] = {\n" % (6 + len(table)))
    out.append("    &pat_ROCK, &pat_POPS, &pat_SWING, &pat_SLOWROCK, &pat_SAMBA, &pat_WALTZ,\n")
    for t in table:
        out.append("    %s,\n" % t)
    out.append("};\n")
    out.append("const mt40_pattern_t *const *mt40_patterns = mt40_pattern_table;\n")
    out.append("const uint8_t mt40_npatterns = %d;\n" % (6 + len(table)))
    text = "".join(out)
    for o in OUTS:
        o.parent.mkdir(parents=True, exist_ok=True)
        o.write_text(text, encoding="utf-8")
    print(f"OK mt40_riddims.c ({len(text)} o, {len(table)} riddims, table {6 + len(table)})")

if __name__ == "__main__":
    gen()
